-- Esquema inicial de Psicometria 369 para PostgreSQL/Supabase.
-- La aplicación accede mediante el servidor Express; la Data API queda cerrada
-- por RLS hasta que se diseñen políticas explícitas para acceso desde navegador.

create type public.user_role as enum ('user', 'admin');
create type public.person_type as enum ('candidate', 'employee');
create type public.person_status as enum ('active', 'archived');
create type public.test_category as enum ('reasoning', 'personality', 'competency');
create type public.test_audience as enum ('operativo', 'mandos_medios', 'todos');
create type public.item_type as enum ('single_choice', 'likert');
create type public.assignment_status as enum ('assigned', 'in_progress', 'completed', 'expired');
create type public.result_level as enum ('bajo', 'medio', 'alto');
create type public.recommendation as enum ('seleccion', 'desarrollo', 'alerta');

create table public.users (
  id integer generated by default as identity primary key,
  "openId" varchar(64) not null unique,
  name text,
  email varchar(320),
  "loginMethod" varchar(64),
  role public.user_role not null default 'user',
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  "lastSignedIn" timestamptz not null default now()
);

create table public.organizations (
  id integer generated by default as identity primary key,
  name varchar(180) not null,
  "legalName" varchar(240),
  address text,
  "privacyContactEmail" varchar(320),
  "privacyChannel" varchar(320),
  "privacyNoticeVersion" varchar(50) not null default 'lfpdppp-mvp-2026-01',
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table public.people (
  id integer generated by default as identity primary key,
  "organizationId" integer not null references public.organizations(id) on delete cascade,
  "userId" integer references public.users(id) on delete set null,
  "fullName" varchar(120) not null,
  email varchar(320) not null,
  "personType" public.person_type not null,
  position varchar(120) not null,
  area varchar(120) not null,
  status public.person_status not null default 'active',
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create unique index people_org_email_unique on public.people ("organizationId", email);
create index people_user_idx on public.people ("userId");

create table public.psychometric_tests (
  id integer generated by default as identity primary key,
  code varchar(50) not null unique,
  name varchar(180) not null,
  category public.test_category not null,
  audience public.test_audience not null,
  "durationMinutes" integer not null,
  instructions text not null,
  "scoringConfig" jsonb not null,
  "isActive" boolean not null default true,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table public.test_dimensions (
  id integer generated by default as identity primary key,
  "testId" integer not null references public.psychometric_tests(id) on delete cascade,
  code varchar(80) not null,
  name varchar(120) not null,
  description text not null,
  "sortOrder" integer not null
);
create unique index test_dimension_unique on public.test_dimensions ("testId", code);
create index dimensions_test_idx on public.test_dimensions ("testId");

create table public.test_items (
  id integer generated by default as identity primary key,
  "testId" integer not null references public.psychometric_tests(id) on delete cascade,
  "dimensionId" integer not null references public.test_dimensions(id) on delete cascade,
  code varchar(80) not null,
  prompt text not null,
  "itemType" public.item_type not null,
  options jsonb not null,
  "reverseScored" boolean not null default false,
  "sortOrder" integer not null,
  "isActive" boolean not null default true
);
create unique index test_item_unique on public.test_items ("testId", code);
create index items_test_idx on public.test_items ("testId");

create table public.evaluation_assignments (
  id integer generated by default as identity primary key,
  "organizationId" integer not null references public.organizations(id) on delete cascade,
  "personId" integer not null references public.people(id) on delete cascade,
  "testId" integer not null references public.psychometric_tests(id) on delete restrict,
  process varchar(120) not null,
  status public.assignment_status not null default 'assigned',
  "consentAccepted" boolean not null default false,
  "consentVersion" varchar(50),
  "startedAt" timestamptz,
  "completedAt" timestamptz,
  "dueAt" timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create index assignments_person_idx on public.evaluation_assignments ("personId");
create index assignments_test_idx on public.evaluation_assignments ("testId");
create index assignments_status_idx on public.evaluation_assignments (status);

create table public.item_responses (
  id integer generated by default as identity primary key,
  "assignmentId" integer not null references public.evaluation_assignments(id) on delete cascade,
  "itemId" integer not null references public.test_items(id) on delete restrict,
  "numericScore" double precision not null,
  "answeredAt" timestamptz not null default now(),
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create unique index assignment_item_unique on public.item_responses ("assignmentId", "itemId");
create index responses_assignment_idx on public.item_responses ("assignmentId");

create table public.evaluation_results (
  id integer generated by default as identity primary key,
  "assignmentId" integer not null unique references public.evaluation_assignments(id) on delete cascade,
  "rawScore" double precision not null,
  "maxScore" double precision not null,
  "scorePercent" double precision not null,
  percentile double precision,
  level public.result_level not null,
  recommendation public.recommendation not null,
  interpretation text not null,
  "dimensionScores" jsonb not null,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table public.privacy_consents (
  id integer generated by default as identity primary key,
  "organizationId" integer not null references public.organizations(id) on delete cascade,
  "personId" integer not null references public.people(id) on delete cascade,
  "assignmentId" integer not null references public.evaluation_assignments(id) on delete cascade,
  "documentVersion" varchar(50) not null,
  "acceptedAt" timestamptz not null default now(),
  method varchar(80) not null,
  "createdAt" timestamptz not null default now()
);
create index consents_assignment_idx on public.privacy_consents ("assignmentId");

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new."updatedAt" = now();
  return new;
end;
$$;

create trigger users_set_updated_at
before update on public.users
for each row execute function public.set_updated_at();

create trigger organizations_set_updated_at
before update on public.organizations
for each row execute function public.set_updated_at();

create trigger people_set_updated_at
before update on public.people
for each row execute function public.set_updated_at();

create trigger psychometric_tests_set_updated_at
before update on public.psychometric_tests
for each row execute function public.set_updated_at();

create trigger evaluation_assignments_set_updated_at
before update on public.evaluation_assignments
for each row execute function public.set_updated_at();

create trigger item_responses_set_updated_at
before update on public.item_responses
for each row execute function public.set_updated_at();

create trigger evaluation_results_set_updated_at
before update on public.evaluation_results
for each row execute function public.set_updated_at();

alter table public.users enable row level security;
alter table public.organizations enable row level security;
alter table public.people enable row level security;
alter table public.psychometric_tests enable row level security;
alter table public.test_dimensions enable row level security;
alter table public.test_items enable row level security;
alter table public.evaluation_assignments enable row level security;
alter table public.item_responses enable row level security;
alter table public.evaluation_results enable row level security;
alter table public.privacy_consents enable row level security;

comment on schema public is
  'Psicometria 369: acceso de datos mediante el servidor, no directamente desde el navegador.';

